    static func draw(in context: CGContext, size: CGSize, color: CGColor) {
        context.saveGState()
        defer { context.restoreGState() }
        fit(context, size: size)
        context.setFillColor(color)
        for layer in layers where !layer.detail {
            context.addPath(layer.head ? expandedHead(layer.path) : layer.path)
            context.fillPath()
        }
        context.setBlendMode(.clear)
        for eye in eyes {
            context.addPath(expandedHead(eye))
            context.fillPath()
        }
    }

    static func drawArtwork(in context: CGContext, size: CGSize) {
        context.saveGState()
        defer { context.restoreGState() }
        fit(context, size: size)
        let colors = [NSColor(red: 85/255, green: 88/255, blue: 97/255, alpha: 1).cgColor,
                      NSColor(red: 48/255, green: 50/255, blue: 57/255, alpha: 1).cgColor,
                      NSColor(red: 25/255, green: 27/255, blue: 32/255, alpha: 1).cgColor] as CFArray
        let gradient = CGGradient(colorsSpace: CGColorSpaceCreateDeviceRGB(), colors: colors,
                                  locations: [0, 0.5, 1])!
        for layer in layers {
            context.saveGState()
            context.addPath(layer.head ? expandedHead(layer.path) : layer.path)
            if layer.detail {
                context.setFillColor(NSColor(red: 119/255, green: 120/255, blue: 125/255, alpha: 0.42).cgColor)
                context.fillPath()
            } else {
                context.clip()
                context.drawLinearGradient(gradient, start: CGPoint(x: -60, y: -90),
                                           end: CGPoint(x: 85, y: 120),
                                           options: [.drawsBeforeStartLocation, .drawsAfterEndLocation])
            }
            context.restoreGState()
        }
        context.setFillColor(NSColor(red: 245/255, green: 244/255, blue: 238/255, alpha: 1).cgColor)
        for eye in eyes { context.addPath(expandedHead(eye)); context.fillPath() }
    }

    // Widen the head around its neck, keeping every arm at its source coordinates.
    private static func expandedHead(_ path: CGPath) -> CGPath {
        var transform = CGAffineTransform(a: 1.28, b: 0, c: 0, d: 1.10, tx: 0, ty: -1.6)
        return path.copy(using: &transform)!
    }

    private static let bounds: CGRect = {
        layers.filter { !$0.detail }.reduce(CGRect.null) {
            $0.union(($1.head ? expandedHead($1.path) : $1.path).boundingBoxOfPath)
        }
    }()

    private static func fit(_ context: CGContext, size: CGSize) {
        let scale = min(size.width / bounds.width, size.height / bounds.height)
        context.translateBy(x: (size.width - bounds.width * scale) / 2,
                            y: (size.height - bounds.height * scale) / 2)
        context.scaleBy(x: scale, y: scale)
        context.translateBy(x: -bounds.minX, y: -bounds.minY)
    }

