/// Base geometry transcribed from the octopus artwork (2026-09-09).
/// Every rendition applies the same head proportions, matching the exported mark.svg.
/// Paths are generated at development time; no SVG parser or bitmap runs in the app.
enum OctopusMark {
    private struct Layer {
        let path: CGPath
        let detail: Bool
        let arm: Int?
        let head: Bool
